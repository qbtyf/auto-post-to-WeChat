// Package config 存放发布所需的凭据。
//
// ══════════════════════════════════════════════════════════════
// ⚠️ 使用前必填！两处凭据见下方 var 块：
//   1. 微信公众号 AppID / AppSecret（必填）
//   2. SSH 服务器（隧道出口，公众号开了 IP 白名单时才需要）
// ══════════════════════════════════════════════════════════════
//
// 【怎么填】两种方式任选：
//
// 方式一（简单）：直接把本文件里的空字符串改成你的值，保存后编译。
//
// 方式二（推荐，密钥不进源码、不进 git 历史）：编译期注入——
//   go build -ldflags "-X wechat-mp-publisher/config.AppID=wx你的appid -X wechat-mp-publisher/config.AppSecret=你的secret"
//
// ⚠️ 安全提醒：AppSecret 等同于公众号的"开发者密码"，任何情况下不要
//    把它提交到 git 仓库、发到群里、或打进分享给别人的 exe。
package config

// ─── ① 微信公众号凭据（必填）───────────────────────────────
// 获取方法：mp.weixin.qq.com 扫码登录 → 设置与开发 → 基本配置 →
//   开发者ID(AppID) 直接可见；开发者密码(AppSecret) 点「生成/重置」
//   并扫码确认后显示（只显示一次，当场保存）。
// 测试号（mp.weixin.qq.com/debug/cgi-bin/sandbox）同样适用。
var (
	AppID     = "" // 例："wx" + 你的16位appid，⚠️ 不要提交真实值到 git
	AppSecret = "" // 32 位字母数字，⚠️ 泄露 = 别人可操作你的公众号
)

// ─── ② SSH 服务器（隧道出口）─────────────────────────────────
// 用途：公众号后台若开启了「IP 白名单」，只有白名单内的 IP 能取
//   access_token。家用宽带 IP 不固定，所以程序通过 SSH 连到你自己的
//   固定 IP 服务器（如云主机），从服务器出口发请求。
// 若你的运行机 IP 本身就在白名单里（固定宽带/办公网），把 ECSHost
//   留空即可走直连（留空 = 不建隧道）。
var (
	ECSHost     = "" // 例："47.x.x.x"，留空 = 不启用隧道
	ECSPort     = "22"
	ECSUser     = "root"
	ECSPassword = "" // 本机 ~/.ssh 有免密私钥（id_ed25519/id_rsa）时留空
)

// ─── ③ 发布相关默认值 ───────────────────────────────────────
var (
	DefaultAuthor = "老齐" // 草稿默认作者名，可改
	BlogURL       = ""    // 文末「阅读原文」跳转链接（留空 = 不设置；建议填你自己的博客/网站）
)
